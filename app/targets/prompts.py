_PROMPTS = {
    "T1": (T1_SYSTEM, T1_HARDENED),
    "T2": (T2_SYSTEM, T2_HARDENED),
    "T3": (T3_SYSTEM, T3_HARDENED),
}


def get_prompt(uid: str, hardened: bool = False, context: str = "") -> str:
    base, hard = _PROMPTS.get(uid, _PROMPTS["T1"])
    tpl = hard if hardened else base
    return tpl.replace("{context}", context or "（无检索结果）")


